// ---- world1Quiz.ts (the quiz bank itself: web-editor/src/data/quizBank/world1Quiz.ts is the only place it is edited)
{
  const source = fs.readFileSync(path.resolve(here, '../src/data/quizBank/world1Quiz.ts'), 'utf8');
  const importLine = "import { QuizQuestion } from '../../utils/quizQuestions';";
  if (!source.includes(importLine)) throw new Error('world1Quiz.ts: expected import line not found; update generate-native-data.ts');
  files['world1Quiz.ts'] =
    '// GENERATED by web-editor/scripts/generate-native-data.ts from web-editor/src/data/quizBank/world1Quiz.ts. Do not edit by hand.\n' +
    source.replace(importLine, "import { QuizQuestion } from './quizQuestions';");
}

const check = process.argv.includes('--check');
let bad = 0;
for (const [name, text] of Object.entries(files)) {
  const file = path.join(OUT, name);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (check) {
    if (current !== text) {
      bad++;
      console.error(`DIFFERS: src/${name}`);
    }
  } else if (current !== text) {
    fs.writeFileSync(file, text);
    console.log(`wrote src/${name}`);
  }
}
if (check) {
  if (bad) {
    console.error(`\n${bad} generated file(s) are out of date. Run: npm run generate:native-data (in web-editor/)`);
    process.exit(1);
  }
  console.log(`Native data is up to date (${Object.keys(files).length} files).`);
}
